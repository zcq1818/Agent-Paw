function loadInstalled(): string[] {
  try {
    const value = JSON.parse(localStorage.getItem(INSTALLED_KEY) || "[]");
    return Array.isArray(value) ? value : [];
  } catch {
    return [];
  }
}

function buildMarkdown(skill: BuiltinSkill) {
  return `---\nname: ${skill.name}\ndescription: ${JSON.stringify(skill.description)}\n---\n\n${skill.body.trim()}\n`;
}

let installing: Promise<boolean> | null = null;

/**
 * 补装还没装过的内置技能。existingNames 是技能文件夹里已有技能的名字（同名的不覆盖用户改过的）。
 * 返回是否写入了新技能（调用方据此决定要不要重新扫描）。
 */
export function installBuiltinSkills(existingNames: string[]): Promise<boolean> {
  if (installing) return installing;
  installing = (async () => {
    const installed = new Set(loadInstalled());
    const existing = new Set(existingNames.map((name) => name.toLowerCase()));
    const pending = BUILTIN_SKILLS.filter((skill) => !installed.has(skill.name));
    if (pending.length === 0) return false;
    // 先记下来：两个窗口同时启动时，另一个窗口读到就不会再装一遍
    pending.forEach((skill) => installed.add(skill.name));
    try {
      localStorage.setItem(INSTALLED_KEY, JSON.stringify([...installed]));
    } catch {}
    let wrote = false;
    for (const skill of pending) {
      if (existing.has(skill.name.toLowerCase())) continue;
      try {
        await invoke("skill_save", { name: skill.name, content: buildMarkdown(skill), existingDir: null });
        wrote = true;
      } catch {
        // 写不进去（比如浏览器预览）就算了，下次也不再试
      }
    }
    return wrote;
  })();
  return installing;
}
